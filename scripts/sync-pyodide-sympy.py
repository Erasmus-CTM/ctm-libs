#!/usr/bin/env python3
"""Record the SymPy that ctm-libs' pinned Pyodide bundles (no dependencies).

ctm-libs owns the Pyodide version (E12): package.json pins the npm package
(package-lock.json binds its integrity) and runtime/pyodide-runtime.js loads
the same release from jsDelivr. Pages import SymPy from that release, so its
SymPy version is a fact of the pin, not a choice. This script reads it from
Pyodide's own lockfile, pyodide-lock.json of the installed npm package (run
`npm ci` first), and writes

  _extensions/ctm-libs/runtime/pyodide-sympy.json   {pyodide, sympy, lockfile sha256}

Components that grade with SymPy at build time in host CPython (ctm-stack's
native PythonCheckers) pin their host SymPy to this file's `sympy`: the
browser refuses a question whose host SymPy differs (python-checker-identity).

  python scripts/sync-pyodide-sympy.py           # write the file
  python scripts/sync-pyodide-sympy.py --check   # fail if it differs or the pins disagree (CI)
"""
import argparse
import hashlib
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
RUNTIME = ROOT / '_extensions' / 'ctm-libs' / 'runtime'
TARGET = RUNTIME / 'pyodide-sympy.json'
PACKAGE = ROOT / 'node_modules' / 'pyodide'


def read_json(path, hint=''):
    try:
        return json.loads(path.read_text())
    except FileNotFoundError:
        raise SystemExit(f'{path.relative_to(ROOT)} is missing{hint}')


def pinned_pyodide():
    """The one Pyodide version of package.json, package-lock.json, the installed package and the runtime."""
    versions = {
        'package.json devDependencies.pyodide': read_json(ROOT / 'package.json').get('devDependencies', {}).get('pyodide'),
        'package-lock.json node_modules/pyodide': read_json(ROOT / 'package-lock.json')['packages'].get('node_modules/pyodide', {}).get('version'),
        'node_modules/pyodide/package.json': read_json(PACKAGE / 'package.json', ' (run npm ci)').get('version'),
    }
    found = re.search(r"\n\s*var indexURL = 'https://cdn\.jsdelivr\.net/pyodide/v([^/']+)/full/';", (RUNTIME / 'pyodide-runtime.js').read_text())
    versions['runtime/pyodide-runtime.js indexURL'] = found[1] if found else None
    if len(set(versions.values())) != 1 or not re.fullmatch(r'\d+\.\d+\.\d+', str(versions['package.json devDependencies.pyodide'])):
        raise SystemExit('The Pyodide pins disagree (or one is not an exact version):\n'
                         + '\n'.join(f'  {where}: {version}' for where, version in versions.items())
                         + '\nPin one exact version in package.json and pyodide-runtime.js, run npm install, then this script.')
    return versions['package.json devDependencies.pyodide']


def expected_text():
    pyodide = pinned_pyodide()
    raw = (PACKAGE / 'pyodide-lock.json').read_bytes()
    sympy = json.loads(raw).get('packages', {}).get('sympy', {})
    if not re.fullmatch(r'\d+(\.\d+)+', str(sympy.get('version'))):
        raise SystemExit(f'pyodide-lock.json of Pyodide {pyodide} has no SymPy version')
    record = {
        'comment': 'Generated by scripts/sync-pyodide-sympy.py from pyodide-lock.json of the pinned Pyodide '
                   '(npm package, integrity in package-lock.json); do not edit. The SymPy pages import. '
                   'Build-time SymPy in host CPython (ctm-stack requirements.txt) must equal `sympy`.',
        'pyodide': pyodide,
        'sympy': sympy['version'],
        'lockfile': {'file': 'pyodide-lock.json', 'sha256': hashlib.sha256(raw).hexdigest()},
    }
    return json.dumps(record, indent=1) + '\n'


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('--check', action='store_true', help='report a difference instead of writing')
    args = parser.parse_args()
    text = expected_text()
    record = json.loads(text)
    old = TARGET.read_text() if TARGET.exists() else None
    if args.check:
        if old != text:
            recorded = json.loads(old) if old else {}
            raise SystemExit(f'{TARGET.relative_to(ROOT)} is out of date: it records Pyodide {recorded.get("pyodide")} '
                             f'with SymPy {recorded.get("sympy")}, the pinned Pyodide {record["pyodide"]} bundles '
                             f'SymPy {record["sympy"]}.\nRun: python scripts/sync-pyodide-sympy.py, and when SymPy changes, '
                             f'pin ctm-stack\'s host SymPy (requirements.txt) to it in the ctm-stack change that repins ctm-libs')
        print(f'Pyodide {record["pyodide"]} bundles SymPy {record["sympy"]}, as {TARGET.relative_to(ROOT)} records')
        return
    if old != text:
        TARGET.write_text(text)
        print('Updated', TARGET.relative_to(ROOT))


if __name__ == '__main__':
    main()
